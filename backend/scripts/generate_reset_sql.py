"""
Write scripts/reset_app_tables.sql: DROP TABLE IF EXISTS for every table the models define,
children before the tables they reference, then alembic_version.

Run from backend/ after the models change:

    python -m scripts.generate_reset_sql

tests/unit/test_reset_app_tables_sql.py fails while the committed file differs from this output.
"""
from pathlib import Path

import app.models  # noqa: F401  (registers every model on the metadata)
from app.core.database import db

_OUTPUT = Path(__file__).resolve().parents[2] / "scripts" / "reset_app_tables.sql"

_HEADER = """\
-- REVIEW THIS FILE BEFORE YOU RUN IT.
--
-- It permanently deletes the application's tables and all the data in them, and the
-- alembic_version table, so that `alembic upgrade head` rebuilds an empty schema.
-- There is no undo. Run it only against a database you mean to empty, and read the project
-- ref in your connection string first.
--
-- It contains DROP TABLE IF EXISTS statements only: no DROP SCHEMA, no CASCADE, and nothing
-- outside the tables listed below (Supabase's own schemas are not touched).
--
-- Generated by `python -m scripts.generate_reset_sql` (from backend/) out of the models'
-- metadata. Do not edit it by hand; change the models and generate it again.
"""


def render() -> str:
    names = [table.name for table in reversed(db.metadata.sorted_tables)] + ["alembic_version"]
    return _HEADER + "\n" + "".join(f'DROP TABLE IF EXISTS "{name}";\n' for name in names)


def main() -> None:
    _OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {_OUTPUT}")


if __name__ == "__main__":
    main()
